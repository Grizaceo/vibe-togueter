// Mock OpenAI-compatible endpoint for testing the generation pipeline.
// Returns a minimal valid game.js for any idea.
import http from 'node:http';

const GAME = `export const meta = { name: 'MockLLM Game', description: 'generated by mock', world: {w:1280,h:720}, tickRate: 30 };
export function createState() { return { __players: new Map(), n: 0 }; }
export function onJoin(state, p) { state.__players.set(p.id, {name: p.name, x: 640, y: 360}); }
export function onLeave(state, p) { state.__players.delete(p.id); }
export function onInput() {}
export function onChat(state, u, cmd) { if (cmd === 'n') { state.n++; return true; } return false; }
export function tick(state, dt) {}
export function view(state) { return { bg: '#001', layers: [{t:'text',x:640,y:360,text:'mock game n='+state.n,size:40,color:'#fff'}], hud: [] }; }
`;

http.createServer((req, res) => {
  if (req.method === 'POST' && req.url === '/v1/chat/completions') {
    let b = ''; req.on('data', c => b += c);
    req.on('end', () => {
      res.writeHead(200, { 'content-type': 'application/json' });
      res.end(JSON.stringify({
        choices: [{ message: { content: '```js\n' + GAME + '```' } }],
        usage: { prompt_tokens: 1200, completion_tokens: 600 },
      }));
    });
  } else { res.writeHead(404); res.end(); }
}).listen(11499, '127.0.0.1', () => console.log('mock llm on :11499'));
